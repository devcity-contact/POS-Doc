"""Build assets/search-index.js from the headings of every page in Doc/.

Usage (from anywhere):  python Doc/tools/build_search_index.py
Each entry: t = heading text, p = page title, u = url#anchor, k = keywords (section text snippet).
Heading ids follow the same slug rule as assets/site.js, so links match.
"""
import html
import json
import pathlib
import re
from html.parser import HTMLParser

DOC = pathlib.Path(__file__).resolve().parent.parent


def slug(text: str) -> str:
    s = re.sub(r"[^a-z0-9\s-]", "", text.lower()).strip()
    return re.sub(r"\s+", "-", s)[:60]


class PageParser(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.title = ""
        self.in_title = False
        self.in_article = False
        self.skip = 0              # inside pre.mermaid / script / style
        self.cur = None            # current heading being read: [tag, id, text]
        self.sections = []         # [tag, id, heading, body]
        self.used = set()

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if tag == "title":
            self.in_title = True
        elif tag == "article":
            self.in_article = True
        elif tag in ("script", "style") or (tag == "pre" and "mermaid" in (a.get("class") or "")):
            self.skip += 1
        elif self.in_article and tag in ("h1", "h2", "h3"):
            self.cur = [tag, a.get("id"), ""]

    def handle_endtag(self, tag):
        if tag == "title":
            self.in_title = False
        elif tag == "article":
            self.in_article = False
        elif tag in ("script", "style") or (tag == "pre" and self.skip):
            self.skip = max(0, self.skip - 1)
        elif self.cur and tag == self.cur[0]:
            htag, hid, text = self.cur
            text = " ".join(text.split())
            if htag != "h1":
                if not hid:
                    hid = slug(text) or "section"
                    while hid in self.used:
                        hid += "-x"
                self.used.add(hid)
            self.sections.append([htag, hid, text, ""])
            self.cur = None

    def handle_data(self, data):
        if self.in_title:
            self.title += data
        if self.skip or not self.in_article:
            return
        if self.cur is not None:
            self.cur[2] += data
        elif self.sections:
            self.sections[-1][3] += " " + data


def main():
    entries = []
    pages = sorted(p for p in DOC.glob("*.html"))
    for page in pages:
        parser = PageParser()
        parser.feed(page.read_text(encoding="utf-8"))
        ptitle = html.unescape(parser.title.split("·")[0].strip())
        for htag, hid, text, body in parser.sections:
            body = " ".join(body.split())[:220]
            url = page.name if htag == "h1" else f"{page.name}#{hid}"
            entries.append({"t": text if htag != "h1" else ptitle, "p": ptitle, "u": url, "k": body})
    out = DOC / "assets" / "search-index.js"
    out.write_text(
        "/* Generated by tools/build_search_index.py; do not edit by hand. */\n"
        "window.SEARCH_INDEX = " + json.dumps(entries, ensure_ascii=False, separators=(",", ":")) + ";\n",
        encoding="utf-8",
    )
    print(f"{len(entries)} entries from {len(pages)} pages -> {out}")


if __name__ == "__main__":
    main()
